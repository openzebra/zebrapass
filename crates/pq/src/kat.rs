fn decode_hex(input: &str) -> Result<Vec<u8>, &'static str> {
    let mut decoded = Vec::new();
    let mut pending = None;
    for byte in input.bytes() {
        if byte.is_ascii_whitespace() {
            continue;
        }
        let value = match byte {
            b'0'..=b'9' => byte - b'0',
            b'a'..=b'f' => byte - b'a' + 10,
            b'A'..=b'F' => byte - b'A' + 10,
            _ => return Err("invalid hex"),
        };
        if let Some(high) = pending {
            decoded.push((high << 4) | value);
            pending = None;
        } else {
            pending = Some(value);
        }
    }
    if pending.is_some() {
        return Err("odd hex length");
    }
    Ok(decoded)
}

#[test]
fn lengths_match_published_sntrup1277() {
    assert_eq!(public_key_bytes(), 2067);
    assert_eq!(secret_key_bytes(), 3059);
    assert_eq!(ciphertext_bytes(), 1847);
}

#[test]
fn rejects_wrong_input_lengths() {
    assert!(matches!(encapsulate(&[]), Err(PqError::PublicKeyLength)));
    let mut long_pk = vec![0_u8; public_key_bytes()];
    long_pk.push(0);
    assert!(matches!(
        encapsulate(&long_pk),
        Err(PqError::PublicKeyLength)
    ));

    let secret_key = vec![0_u8; secret_key_bytes()];
    assert!(matches!(
        decapsulate(&[], &[]),
        Err(PqError::SecretKeyLength)
    ));
    assert!(matches!(
        decapsulate(&secret_key, &[]),
        Err(PqError::CiphertextLength)
    ));
    let mut long_ct = vec![0_u8; ciphertext_bytes()];
    long_ct.push(0);
    assert!(matches!(
        decapsulate(&secret_key, &long_ct),
        Err(PqError::CiphertextLength)
    ));
}

#[test]
fn published_decapsulation_vector() -> Result<(), &'static str> {
    let sk = decode_hex(SK_HEX)?;
    let ct = decode_hex(CT_HEX)?;
    let ss = decode_hex(SS_HEX)?;
    assert_eq!(sk.len(), secret_key_bytes());
    assert_eq!(ct.len(), ciphertext_bytes());
    assert_eq!(ss.len(), 32);
    let opened = decapsulate(&sk, &ct).map_err(|_| "decapsulate")?;
    assert_eq!(opened.expose().as_slice(), ss.as_slice());
    Ok(())
}

#[test]
fn well_sized_ciphertext_is_not_an_error() -> Result<(), &'static str> {
    let sk = decode_hex(SK_HEX)?;
    let mut ct = decode_hex(CT_HEX)?;
    if let Some(last) = ct.last_mut() {
        *last ^= 1;
    }
    let opened = decapsulate(&sk, &ct).map_err(|_| "implicit rejection")?;
    assert_eq!(opened.expose().len(), 32);
    Ok(())
}

#[test]
fn encapsulate_then_decapsulate_roundtrip() -> Result<(), PqError> {
    let (pk, sk) = keypair();
    let (shared, ciphertext) = encapsulate(pk.as_bytes())?;
    assert_eq!(ciphertext.len(), ciphertext_bytes());
    let opened = decapsulate(sk.as_bytes(), &ciphertext)?;
    assert_eq!(shared.expose(), opened.expose());
    Ok(())
}
